def main(argv: list[str] | None = None) -> int:
    global OUT, IMG
    parser = argparse.ArgumentParser(description="Збірка звітів з лабораторних робіт у форматі .docx")
    parser.add_argument("labs", nargs="*", type=int, help="номери робіт (за замовчуванням усі)")
    parser.add_argument("--student", default=META["student"])
    parser.add_argument("--group", default=META["group"])
    parser.add_argument("--teacher", default=META["teacher"])
    parser.add_argument("--year", default=META["year"])
    parser.add_argument("--out", default=str(OUT))
    parser.add_argument("--no-pdf", action="store_true", help="не створювати PDF-версії")
    args = parser.parse_args(argv)
    meta = dict(META, student=args.student, group=args.group, teacher=args.teacher, year=args.year)
    OUT = Path(args.out)
    IMG = OUT / "img"
    Report.pdf_default = not args.no_pdf
    numbers = args.labs or sorted(BUILDERS)
    for number in numbers:
        path = BUILDERS[number](meta)
        suffix = "" if args.no_pdf else " (+ {})".format(path.with_suffix(".pdf").name)
        print("✓ ЛР {} → {}{}".format(number, path.name, suffix))
    return 0


