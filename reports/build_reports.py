    rep.table(["Підприємство"] + ["№ {}".format(i + 1) for i in range(F.shape[0])] + ["Разом"],
              [["Вкладення, грош. од."] + [fmt(v) for v in alloc] + [fmt(float(sum(alloc)))],
               ["Приріст випуску"] + [fmt(F[i, int(alloc[i] // 20) - 1]) if alloc[i] > 0 else "0"
                                      for i in range(F.shape[0])] + [fmt(seq.get("F"))]],
              "Оптимальний розподіл капіталовкладень")
    rep.figure(s.plot(IMG / "lab9_plot.png", 0), "Функції відгуку підприємств", 13.0)
    best = [i + 1 for i in range(F.shape[0]) if alloc[i] > 0]
    rep.conclusions([
        "у роботі набуто навичок розв’язування задач розподілу обмежених ресурсів методами динамічного "
        "програмування. Обома методами – послідовним (за рекурентними співвідношеннями Беллмана) і за вартістю "
        "переходу – отримано однаковий оптимальний розподіл ({}) з максимальним приростом випуску продукції "
        "F = {}.".format("; ".join(fmt(v) for v in alloc), fmt(seq.get("F"))),
        "Усі кошти доцільно вкласти в підприємства № {}, оскільки їх функції відгуку мають найбільший приріст на "
        "великих обсягах інвестицій; підприємства з майже лінійною функцією відгуку в оптимальний план не "
        "ввійшли.".format(", ".join(str(i) for i in best)),
        "Збіг результатів двох методів підтверджує правильність обчислень, а сам принцип оптимальності Беллмана "
        "дозволив замінити перебір усіх варіантів розподілу послідовністю одновимірних задач."])
    return rep.save(OUT / "ЛР9 Розподіл обмежених ресурсів.docx")


