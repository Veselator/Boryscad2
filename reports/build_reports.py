def lab3(meta: dict) -> Path:
    s = Sheet("lab3_nonlinear.bmath")
    pmin, pmax = s.value("Pmin"), s.value("Pmax")
    f = lambda a, b: s.call("f", float(a), float(b))
    fmin, fmax = s.call("φ", float(s.value("tmin"))), s.call("φ", float(s.value("tmax")))
    rep = Report(3, "Задача нелінійного програмування",
                 "набути навичок з розв’язування двовимірних задач нелінійного програмування.", meta)
    rep.para("Для варіанта 21 (N = 21, k = 2) потрібно визначити мінімальне й максимальне значення функції")
    rep.formula("f(x₁, x₂) = x₁² − k·N·x₁ + x₂² = x₁² − 42·x₁ + x₂²")
    rep.para("за умови виконання обмежень")
    rep.formula("x₁² + x₂² ≤ N² = 441")
    rep.formula("x₂ = N·x₁ = 21·x₁")
    rep.formula("x₁ ≥ 0,  x₂ ≥ 0")
    rep.note("де N = 21 – номер студента у журналі успішності; k = 2 – коефіцієнт, заданий викладачем.")
    rep.heading("1 Розв’язання графічним методом")
    rep.para("На координатній площині побудовано лінії рівня цільової функції (концентричні кола з центром у точці "
             "(21; 0)), коло обмеження x₁² + x₂² = 441, промінь x₂ = 21·x₁ та область допустимих розв’язків. "
             "Оскільки обмеження-рівність зводить задачу до відрізка прямої, екстремуми знаходяться у точках дотику "
             "ліній рівня до цього відрізка та на його кінці.")
    rep.figure(s.plot(IMG / "lab3_plot.png", 0), "Лінії рівня функції, область допустимих розв’язків і точки екстремуму", 14.0)
    rep.heading("2 Розв’язання в пакеті Boryscad")
    rep.para("Задачу розв’язано блоком given з обмеженнями та функціями minimize і maximize. Лістинг розрахунку "
             "наведено на рисунку 2.")
    rep.figure(s.listing(IMG / "lab3_listing.png", contains=["given", "f(x1, x2) :=", "Pmin ="]),
               "Лістинг розрахунку задачі нелінійного програмування", 12.5)
    rep.heading("3 Перевірка отриманих розв’язків")
    rep.para("Підставивши x₂ = 21·x₁ у цільову функцію, отримаємо функцію однієї змінної:")
    rep.formula("φ(t) = t² − 42·t + (21·t)² = 442·t² − 42·t")
    rep.para("Умова екстремуму φ′(t) = 884·t − 42 = 0 дає точку мінімуму")
    rep.formula("t_min = k·N / (2·(1 + N²)) = 21/442 = {}".format(s.num("tmin")))
    rep.para("Оскільки парабола опукла вгору за t, максимум досягається на межі області – у точці перетину прямої "
             "з колом обмеження:")
    rep.formula("t_max = N / √(1 + N²) = 21/√442 = {}".format(s.num("tmax")))
    rep.table(["Величина", "Блок given (чисельно)", "Аналітично", "Розбіжність"],
              [["x₁ мінімуму", fmt(pmin[0]), s.num("tmin"), fmt(abs(float(pmin[0]) - float(s.value("tmin"))), 2)],
               ["x₂ мінімуму", fmt(pmin[1]), fmt(21 * float(s.value("tmin"))), "≈ 0"],
               ["f мінімальне", fmt(f(pmin[0], pmin[1])), fmt(fmin), "≈ 0"],
               ["x₁ максимуму", fmt(pmax[0]), s.num("tmax"), "≈ 0"],
               ["x₂ максимуму", fmt(pmax[1]), fmt(21 * float(s.value("tmax"))), "≈ 0"],
               ["f максимальне", fmt(f(pmax[0], pmax[1])), fmt(fmax), "≈ 0"]],
              "Порівняння чисельного та аналітичного розв’язків")
    rep.conclusions([
        "у роботі набуто навичок розв’язування двовимірних задач нелінійного програмування. Задачу для варіанта 21 "
        "розв’язано графічним методом і в пакеті Boryscad за допомогою блоку given: мінімум f = {} досягається в "
        "точці ({}; {}), максимум f = {} – у точці ({}; {}).".format(
            fmt(f(pmin[0], pmin[1])), fmt(pmin[0]), fmt(pmin[1]),
            fmt(f(pmax[0], pmax[1])), fmt(pmax[0]), fmt(pmax[1])),
        "Обмеження-рівність x₂ = 21·x₁ перетворює задачу на одновимірну: цільова функція вздовж цього променя є "
        "параболою φ(t) = 442·t² − 42·t. Її вершина лежить усередині допустимої області й дає мінімум, а максимум "
        "досягається на межі – у точці перетину променя з колом x₁² + x₂² = 441, тобто є граничним.",
        "Перевірка аналітичним методом повністю підтвердила чисельні результати (розбіжність не перевищує похибки "
        "округлення), що свідчить про достовірність отриманих розв’язків."])
    return rep.save(OUT / "ЛР3 Задача нелінійного програмування.docx")


