def _add_tables(rep: Report, sheet: Sheet, record: str, captions: dict[int, str], size=SMALL,
                only: list[int] | None = None) -> None:
    tables = sheet.tables(record)
    for i, table in enumerate(tables):
        if only is not None and i not in only:
            continue
        headers, rows = sheet.rows(table)
        rep.table(headers, rows, captions.get(i, uk(table.title)), size=size)


