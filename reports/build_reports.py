def lab9(meta: dict) -> Path:
    s = Sheet("lab9_allocation.bmath")
    F = s.value("F")
    seq, graph = s.record("s"), s.record("g")
    alloc = seq.get("x")
    rep = Report(9, "Розподіл обмежених ресурсів",
                 "набути навичок розв’язування задач розподілу обмежених ресурсів за допомогою динамічного "
                 "програмування.", meta)
    rep.para("Для збільшення обсягів випуску продукції виділено капіталовкладення в обсязі S = 5 у.о. "
             "(1 у.о. = 20 грошових одиниць). Використання i-м підприємством xᵢ коштів забезпечує приріст випуску "
             "продукції φᵢ(xᵢ). Значення функцій відгуку для варіанта 21 (варіант 1 табл. 9) наведено в таблиці 1.")
    headers, rows = s.matrix_rows(F, ["20", "40", "60", "80", "100"],
                                  ["φ{}(x)".format(i + 1) for i in range(F.shape[0])], precision=0)
    rep.table(headers, rows, "Функції відгуку підприємств")
    rep.heading("1 Математична постановка задачі")
    rep.formula("F = Σ fᵢ(xᵢ) → max")
    rep.formula("Σ xᵢ = S,  xᵢ ≥ 0,  i = 1, n")
    rep.note("де xᵢ – кошти, виділені i-му підприємству; S = 100 грошових одиниць (5 у.о.); n = {} – кількість "
             "підприємств.".format(F.shape[0]))
    rep.heading("2 Послідовний метод (рекурентні співвідношення Беллмана)")
    rep.para("Задачу розв’язано як багатокрокову: досліджено ефективність вкладення коштів спочатку на одному "
             "підприємстві, потім на двох і т. д. Рекурентні співвідношення Беллмана:")
    rep.formula("φ₁(X) = f₁(X)")
    rep.formula("φₖ(X) = max { fₖ(x) + φₖ₋₁(X − x) },  0 ≤ x ≤ X")
    _add_tables(rep, s, "s", {})
    rep.para("Зворотним ходом за позначеними клітинками відновлено оптимальний розподіл коштів.")
    rep.heading("3 Метод за вартістю переходу")
    rep.para("Задачу подано у вигляді мережі станів (k, s), де k – номер етапу (підприємства), s – сума вже "
             "вкладених коштів. Вага дуги дорівнює приросту випуску продукції на відповідному підприємстві, а "
             "оптимальному розподілу відповідає шлях максимальної ваги зі стану (0; 0) до стану (n; S).")
