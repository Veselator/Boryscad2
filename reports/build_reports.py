"""Builds the nine lab reports (.docx) from the Boryscad worksheets.

    python reports/build_reports.py                       # all reports → reports/out
    python reports/build_reports.py 3 7 --student "Іванов І. І." --group КН-24-1

Every number, table and picture comes from the worksheet in boryscad/examples,
so re-running after a change of N or k produces a consistent report.
"""
from __future__ import annotations

