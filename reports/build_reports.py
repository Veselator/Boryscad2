def lab2(meta: dict) -> Path:
    s = Sheet("lab2_simplex.bmath")
    z, r, Z = s.value("z"), s.value("r"), s.value("Z")
    sim, lp = s.record("s"), s.record("lp")
    x = sim.get("x")
    rep = Report(2, "Задача планування оптимального виробництва",
                 "набути навичок з розв’язування багатомірних задач лінійного програмування симплекс-методом.", meta)
    rep.para("Задача містить 5 вихідних змінних і 5 обмежень. Згідно із завданням коефіцієнти витрати ресурсів "
             "обчислено як ROUND(RAND()·N·k; 0), коефіцієнти цільової функції – як ROUND(RAND()·10; 0), а ліміти "
             "ресурсів – за формулами Z = (100; 150; 120; 200; 80)·N·k для варіанта 21 (N = 21, k = 2).")
    headers = ["Ресурс", "x₁", "x₂", "x₃", "x₄", "x₅", "Запаси"]
    rows = [["Ресурс {}".format(i + 1)] + [fmt(v) for v in z[i]] + [fmt(Z[i])] for i in range(z.shape[0])]
    rows.append(["Цільова функція"] + [fmt(v) for v in r] + ["max"])
    rep.table(headers, rows, "Опорний план задачі (витрата ресурсів, прибуток і запаси)")
    rep.heading("1 Математична модель")
    rep.formula("R = " + " + ".join("{}·x{}".format(fmt(r[j]), chr(0x2081 + j)) for j in range(len(r))) + " → max")
    rep.para("Система рівнянь обмежень:")
    for i in range(z.shape[0]):
        rep.formula(" + ".join("{}·x{}".format(fmt(z[i, j]), chr(0x2081 + j)) for j in range(z.shape[1]))
                    + " ≤ {}".format(fmt(Z[i])), numbered=i == 0)
    rep.formula("xⱼ ≥ 0,  j = 1, 5")
    rep.heading("2 Розв’язання симплекс-методом")
    rep.para("До кожного обмеження додано базисну (слабку) змінну sᵢ, після чого складено симплекс-таблицю. "
             "Базисну змінну для введення обрано за найбільшим за модулем від’ємним значенням рядка Δ, а базисний "
             "рядок – за найменшим додатним симплексним відношенням θ. Ітераційний процес припинено, коли в рядку Δ "
             "не залишилося від’ємних значень.")
    _add_tables(rep, s, "s", {}, size=SMALL)
    rep.heading("3 Оптимальний розв’язок і залишки ресурсів")
    rep.formula("X* = (" + "; ".join(fmt(v) for v in x) + "),   R = {}".format(fmt(sim.get("F"))))
    used = z @ x
    rep.table(["Ресурс", "Запас", "Використано", "Залишок"],
              [["Ресурс {}".format(i + 1), fmt(Z[i]), fmt(used[i]), fmt(sim.get("remainder")[i])]
               for i in range(z.shape[0])],
              "Залишки за використаними ресурсами")
    rep.para("Для перевірки задачу додатково розв’язано вбудованим розв’язувачем (метод HiGHS): отримано "
             "R = {}, що збігається з результатом симплекс-методу.".format(fmt(lp.get("F"))))
    rep.figure(s.listing(IMG / "lab2_listing.png", contains=["z :=", "Z :="], page_width=460.0),
               "Лістинг формування опорного плану та розрахунку в пакеті Boryscad", 12.5)
    binding = [i + 1 for i in range(z.shape[0]) if abs(float(sim.get("remainder")[i])) < 1e-9]
    rep.conclusions([
        "у роботі набуто навичок розв’язування багатомірних задач лінійного програмування симплекс-методом. "
        "Для згенерованих за варіантом 21 даних складено опорний план, уведено базисні змінні та виконано {} "
        "симплекс-ітерацій до отримання оптимального плану X* = ({}) з максимальним прибутком "
        "R = {}.".format(sim.get("iterations"), "; ".join(fmt(v) for v in x), fmt(sim.get("F"))),
        "Повністю використано ресурси {}; інші ресурси мають залишки, тобто не обмежують випуск продукції. "
        "Результат симплекс-методу збігається з розв’язком, отриманим незалежним розв’язувачем, що підтверджує "
        "коректність обчислень.".format(", ".join("№ " + str(i) for i in binding) or "відсутні"),
        "Аналіз розв’язку показує, що у виробничу програму ввійшли не всі види продукції: змінні, які дорівнюють "
        "нулю, невигідні за наявного співвідношення витрат ресурсів і прибутку."])
    return rep.save(OUT / "ЛР2 Симплекс-метод.docx")


